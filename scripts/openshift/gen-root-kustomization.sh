#!/usr/bin/env bash
# Write the repo-root kustomization.yaml that Argo CD builds for the OpenShift workloads:
# the overlays in deploy/openshift/apps plus the ConfigMaps that k3d's up.sh creates with
# `kubectl create configmap --from-file=<dir>`. It lives at the root because Kustomize only
# reads files under the kustomization's own directory, and the sources are in scenarios/,
# policy/ and gateway/. Kustomize can't take a directory, so every file is listed; --check fails if
# the committed file differs from what this script would write (a fixture added or removed).
#
# Usage: scripts/openshift/gen-root-kustomization.sh [--check]
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
OUT="$ROOT/kustomization.yaml"

files() { (cd "$ROOT" && find "$@" -maxdepth 1 -type f | LC_ALL=C sort | sed 's/^/      - /'); }

render() {
  cat <<EOF
# OpenShift workloads for Argo CD (OS-08), built from the repo root so the ConfigMaps can
# read scenarios/, policy/ and gateway/ in place (D-054). Generated by
# scripts/openshift/gen-root-kustomization.sh; don't edit by hand. k3d doesn't use it.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - deploy/openshift/apps/ai
  - deploy/openshift/apps/gateway
generatorOptions:
  disableNameSuffixHash: true   # the workloads mount these by name, as on k3d
configMapGenerator:
  - name: mock-llm-scripts
    namespace: aigw-ai
    files:
$(files scenarios/fixtures/mock-llm)
  - name: fixtures-documents
    namespace: aigw-ai
    files:
$(files scenarios/fixtures/documents)
  - name: fixtures-records
    namespace: aigw-ai
    files:
      - scenarios/fixtures/records.json
  # What the console restores (D-043)
  - name: guard-policy-baseline
    namespace: aigw-ai
    files:
      - policy/policy.yaml
  # The live policy: created from git once, then changed by the console and make
  # policy-set. The Application ignores its data, so a sync never reverts those changes.
  - name: guard-policy
    namespace: aigw-ai
    options:
      annotations: {argocd.argoproj.io/sync-options: Prune=false}
    files:
      - policy/policy.yaml
  # APISIX's custom Lua plugins, one ConfigMap each (the chart names a volume per ConfigMap)
$(cd "$ROOT" && for f in $(LC_ALL=C ls gateway/plugins/*.lua); do
    printf '  - name: apisix-plugin-%s\n    namespace: aigw-gateway\n    files:\n      - %s\n' "$(basename "$f" .lua)" "$f"
  done)
EOF
}

if [[ "${1:-}" == --check ]]; then
  diff -u "$OUT" <(render) >&2 || { echo "kustomization.yaml is stale: run scripts/openshift/gen-root-kustomization.sh" >&2; exit 1; }
  echo "kustomization.yaml is up to date"
else
  render >"$OUT"
  echo "wrote $OUT"
fi
