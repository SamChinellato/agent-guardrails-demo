#!/usr/bin/env bash
# Write the repo-root kustomization.yaml that Argo CD builds for the OpenShift workloads:
# the overlays in deploy/openshift/apps plus the ConfigMaps that k3d's up.sh creates with
# `kubectl create configmap --from-file=<dir>`. It lives at the root because Kustomize only
# reads files under the kustomization's own directory, and the sources are in scenarios/,
# policy/ and gateway/. Kustomize can't take a directory, so every file is listed; --check fails if
# the committed file differs from what this script would write (a fixture added or removed).
#
# Usage: scripts/openshift/gen-root-kustomization.sh [--check]
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
OUT="$ROOT/kustomization.yaml"

files() { (cd "$ROOT" && find "$@" -maxdepth 1 -type f | LC_ALL=C sort | sed 's/^/      - /'); }

render() {
  cat <<EOF
# OpenShift workloads and telemetry for Argo CD (OS-08), built from the repo root so the
# ConfigMaps and alert rules can read scenarios/, policy/, gateway/ and observability/ in
# place (D-054). Generated by
# scripts/openshift/gen-root-kustomization.sh; don't edit by hand. k3d doesn't use it.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - deploy/openshift/apps/ai
  - deploy/openshift/apps/gateway
  - deploy/openshift/apps/networkpolicies.yaml
  - deploy/openshift/telemetry
  # The k3d alert rules, unchanged but for the API group (OS-01, KS-10)
  - observability/alerts/killswitch.yaml
patches:
  - target: {group: monitoring.coreos.com, kind: PrometheusRule}
    patch: |-
      - {op: replace, path: /apiVersion, value: monitoring.rhobs/v1}
      - {op: replace, path: /metadata/namespace, value: aigw-observability}
      - {op: add, path: /metadata/labels, value: {app.kubernetes.io/part-of: ai-gateway-demo}}
generatorOptions:
  disableNameSuffixHash: true   # the workloads mount these by name, as on k3d
configMapGenerator:
  - name: mock-llm-scripts
    namespace: aigw-ai
    files:
$(files scenarios/fixtures/mock-llm)
  - name: fixtures-documents
    namespace: aigw-ai
    files:
$(files scenarios/fixtures/documents)
  - name: fixtures-records
    namespace: aigw-ai
    files:
      - scenarios/fixtures/records.json
  # What the console restores (D-043)
  - name: guard-policy-baseline
    namespace: aigw-ai
    files:
      - policy/policy.yaml
  # The live policy: created from git once, then changed by the console and make
  # policy-set. The Application ignores its data, so a sync never reverts those changes.
  - name: guard-policy
    namespace: aigw-ai
    options:
      annotations: {argocd.argoproj.io/sync-options: Prune=false}
    files:
      - policy/policy.yaml
  # gguf-fetch and llama.cpp's verify-model step (OS-16): the script and the pinned hashes
  - name: model-fetch
    namespace: aigw-ai
    files:
      - deploy/openshift/llm/fetch_model.py
      - deploy/openshift/llm/granite-4.0-micro-gguf.sha256
  # The LLM mode the gateway-bootstrap Job applies (D-060): live on a fresh install, then
  # switched by make llm-mode. The Application ignores its data, like guard-policy.
  - name: llm-mode
    namespace: aigw-gateway
    options:
      annotations: {argocd.argoproj.io/sync-options: Prune=false}
    literals:
      - mode=live
  # APISIX's custom Lua plugins, one ConfigMap each (the chart names a volume per ConfigMap)
$(cd "$ROOT" && for f in $(LC_ALL=C ls gateway/plugins/*.lua); do
    printf '  - name: apisix-plugin-%s\n    namespace: aigw-gateway\n    files:\n      - %s\n' "$(basename "$f" .lua)" "$f"
  done)
  # Grafana dashboards (OBS-05), unchanged from k3d; dashboards.yaml points one
  # GrafanaDashboard at each
$(cd "$ROOT" && for f in $(LC_ALL=C ls observability/dashboards/*.json); do
    printf '  - name: dashboard-%s\n    namespace: aigw-observability\n    files:\n      - %s\n' "$(basename "$f" .json)" "$f"
  done)
  # gateway/ for the gateway-bootstrap Job (OS-10), one ConfigMap per kind, mounted at
  # /gateway/<kind> (ConfigMap keys can't hold a path)
$(cd "$ROOT" && for d in consumers plugin_configs plugin_metadata routes upstreams; do
    printf '  - name: gateway-%s\n    namespace: aigw-gateway\n    files:\n' "${d//_/-}"
    files "gateway/$d"
  done)
EOF
}

# One GrafanaDashboard per dashboard ConfigMap
DASH="$ROOT/deploy/openshift/telemetry/dashboards.yaml"
render_dashboards() {
  echo "# Generated by scripts/openshift/gen-root-kustomization.sh; don't edit by hand."
  echo "# One GrafanaDashboard per observability/dashboards/*.json (ConfigMap dashboard-<name>)."
  local first=1 f n
  for f in $(cd "$ROOT" && LC_ALL=C ls observability/dashboards/*.json); do
    n="$(basename "$f" .json)"
    (( first )) || echo "---"; first=0
    cat <<EOF
apiVersion: grafana.integreatly.org/v1beta1
kind: GrafanaDashboard
metadata: {name: $n, namespace: aigw-observability}
spec:
  instanceSelector: {matchLabels: {dashboards: aigw}}
  resyncPeriod: 1m   # Grafana's storage is an emptyDir: re-apply soon after a restart
  configMapRef: {name: dashboard-$n, key: $n.json}
EOF
  done
}

if [[ "${1:-}" == --check ]]; then
  diff -u "$OUT" <(render) >&2 || { echo "kustomization.yaml is stale: run scripts/openshift/gen-root-kustomization.sh" >&2; exit 1; }
  diff -u "$DASH" <(render_dashboards) >&2 || { echo "dashboards.yaml is stale: run scripts/openshift/gen-root-kustomization.sh" >&2; exit 1; }
  echo "kustomization.yaml and dashboards.yaml are up to date"
else
  render >"$OUT"
  render_dashboards >"$DASH"
  echo "wrote $OUT and $DASH"
fi
